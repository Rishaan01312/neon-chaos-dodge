  async function submitLegacyBestScore(playerName) {
    if (safeLocalStorageGet(LEGACY_BEST_MIGRATED_KEY) === "1") return;

    const bestScore = Number(
      typeof window.getBestScore === "function"
        ? window.getBestScore()
        : safeLocalStorageGet(LEGACY_BEST_KEY)
    );
    if (!Number.isFinite(bestScore) || bestScore <= 0) {
      safeLocalStorageSet(LEGACY_BEST_MIGRATED_KEY, "1");
      return;
    }

    if (bestScore > MAX_SCORE) return;

    try {
      const response = await fetch(API_URL, {
        method: "POST",
        body: JSON.stringify({
          name: playerName,
          score: Math.floor(bestScore)
        })
      });

      if (!response.ok) {
        throw new Error(`Legacy best score upload failed: ${response.status}`);
      }

      safeLocalStorageSet(LEGACY_BEST_MIGRATED_KEY, "1");
      await loadLeaderboard();
      window.showToast && window.showToast("Your best score has been saved to the leaderboard!");
    } catch (error) {
      console.warn("Legacy best score upload failed:", error);
    }
  }

