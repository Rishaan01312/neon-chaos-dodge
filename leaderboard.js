  function createIdentifier() {
    if (window.crypto && window.crypto.randomUUID) return window.crypto.randomUUID();
    return `${Date.now().toString(36)}-${Math.random().toString(36).slice(2)}`;
  }

  function getPlayerId() {
    if (cachedPlayerId) return cachedPlayerId;

    cachedPlayerId = safeLocalStorageGet(PLAYER_ID_KEY);
    if (!cachedPlayerId) {
      cachedPlayerId = createIdentifier();
      safeLocalStorageSet(PLAYER_ID_KEY, cachedPlayerId);
    }
    return cachedPlayerId;
  }

  function sanitizeName(rawName) {
    const trimmed = String(rawName ?? "").trim().replace(/\s+/g, " ");
    return trimmed.slice(0, MAX_NAME_LENGTH);
  }

  function containsProfanity(name) {
    const cleanName = sanitizeName(name).toLowerCase();
    const words = cleanName.match(/[a-z0-9]+/g) || [];
    return PROFANITY_LIST.some((word) => words.includes(word));
  }

  function formatRankLabel(rank) {
    const suffixes = ["th", "st", "nd", "rd"];
    const value = rank % 100;
    const suffix = suffixes[(value - 20) % 10] || suffixes[value] || suffixes[0];
    return `${rank}${suffix}`;
  }

